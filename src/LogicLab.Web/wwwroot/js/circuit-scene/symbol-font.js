let loading;

export function loadSymbolFont() {
  loading ??= loadVerifiedFace().catch((error) => {
    loading = null;
    throw error;
  });
  return loading;
}

async function loadVerifiedFace() {
  const response = await fetch(symbolFontUrl);
  if (!response.ok) {
    throw new Error("fontUnavailable");
  }
  const bytes = await response.arrayBuffer();
  const digest = await crypto.subtle.digest("SHA-256", bytes);
  const fingerprint = Array.from(new Uint8Array(digest), (value) =>
    value.toString(16).padStart(2, "0"),
  ).join("");
  if (fingerprint !== symbolFontAssetFingerprint) {
    throw new Error("assetFingerprintMismatch");
  }
  const face = await new FontFace(symbolFontFamily, bytes, { weight: "400" }).load();
  document.fonts.add(face);
  return face;
}

export function packagedFontSupports(text) {
  for (const character of text) {
    const codePoint = character.codePointAt(0);
    let lower = 0;
    let upper = packagedFontCodePointRanges.length - 1;
    let supported = false;
    while (lower <= upper) {
      const middle = Math.floor((lower + upper) / 2);
      const [minimum, maximum] = packagedFontCodePointRanges[middle];
      if (codePoint < minimum) {
        upper = middle - 1;
      } else if (codePoint > maximum) {
        lower = middle + 1;
      } else {
        supported = true;
        break;
      }
    }
    if (!supported) {
      return false;
    }
  }
  return true;
}
